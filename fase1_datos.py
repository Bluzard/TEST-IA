def comparar():
    from tokenizers import Tokenizer

    t1, t2 = Tokenizer.from_file(str(TOK_V1)), Tokenizer.from_file(str(TOK_V2))
    bloques = _bloques_de_comparacion()
    print("\nTokens por palabra y por 100 caracteres, v1 (16 k) vs v2 (24 k), sobre texto RESERVADO (no vio la muestra de entrenamiento):")
    print(f"{'dominio':24s} {'docs':>5s} {'palabras':>10s}   {'v1 tok/pal':>10s} {'v2 tok/pal':>10s} {'cambio':>8s}   {'v1 tok/100c':>11s} {'v2 tok/100c':>11s}")
    res = {}
    for nombre, docs in bloques.items():
        if not docs:
            continue
        pal = sum(len(d.split()) for d in docs)
        car = sum(len(d) for d in docs)
        n1 = sum(len(e.ids) for e in t1.encode_batch(docs))
        n2 = sum(len(e.ids) for e in t2.encode_batch(docs))
        res[nombre] = dict(docs=len(docs), palabras=pal, caracteres=car, v1_tokens=n1, v2_tokens=n2, v1_tok_por_palabra=n1 / pal, v2_tok_por_palabra=n2 / pal)
        print(f"{nombre:24s} {len(docs):5d} {pal:10d}   {n1 / pal:10.3f} {n2 / pal:10.3f} {(n2 / n1 - 1):+8.1%}   {100 * n1 / car:11.2f} {100 * n2 / car:11.2f}")
    # símbolos y sintaxis de código, tildes: tokenización limpia y reversible
    casos = ["x**2", "y = x**2 + 3*x - 1", "{'a': 1, 'b': [1, 2, 3]}", "def f(n):\n    return n * 2\n", "if x == 0:\n\tprint('cero')", "for i in range(10):\n    for j in range(i):\n        pass",
             "[x**2 for x in range(1, 6)]", "a != b and c >= d or e <= f", "SELECT nombre FROM clientes WHERE edad > 18;", "console.log(`Hola ${nombre}`);", "<div class=\"caja\">¡Hola!</div>",
             "función, canción, ñandú, güiro, ¿Qué tal? ¡Genial! —dijo Ana—.", "Él compró más café; tú también.", "https://es.wikipedia.org/wiki/Chile#Historia", "pandas.DataFrame().groupby('a').sum()",
             "np.array([[1, 2], [3, 4]]) @ np.eye(2)", "A -> B => C == D", "    return x  # comentario", "TEST-IA", "Corrige: ayer fui al mercado"]
    print("\nSímbolos, sintaxis de código y tildes (todos deben recuperarse EXACTAMENTE al decodificar):")
    ok_total = True
    filas = []
    for s in casos:
        e1, e2 = t1.encode(s), t2.encode(s)
        d2 = t2.decode(e2.ids)
        ok = d2 == s
        ok_total &= ok
        filas.append({"texto": s, "v1": len(e1.ids), "v2": len(e2.ids), "ok": ok, "tokens_v2": e2.tokens})
        print(f"  {'OK ' if ok else 'MAL'} v1 {len(e1.ids):3d} -> v2 {len(e2.ids):3d} tokens  {s[:46]!r:50s} {e2.tokens[:12] if len(e2.ids) <= 12 else ''}")
    # degeneración: ningún token «raro» único para operadores comunes, y los de dos caracteres no se parten
    vocab = t2.get_vocab()
    chequeos = {"«**» es un solo token (con o sin espacio delante)": len(t2.encode("**").ids) == 1 or len(t2.encode(" **").ids) == 1, "«==» es un solo token (con o sin espacio delante)": len(t2.encode("==").ids) == 1 or len(t2.encode(" ==").ids) == 1, "«!=» es un solo token (con o sin espacio delante)": len(t2.encode("!=").ids) == 1 or len(t2.encode(" !=").ids) == 1, "«->» es un solo token (con o sin espacio delante)": len(t2.encode("->").ids) == 1 or len(t2.encode(" ->").ids) == 1,
                "indentación de 4 espacios cabe en 1-2 tokens": len(t2.encode("\n    return x").ids) <= 4,
                "«ñ», «á», «¿» existen como tokens": all(c in "".join(vocab) or t2.token_to_id(c) is not None for c in "ñá¿¡"),
                "x**2 en ≤ 3 tokens": len(t2.encode("x**2").ids) <= 3}
    for k, v in chequeos.items():
        print(f"  {'OK ' if v else 'MAL'} {k}")
        ok_total &= v
    print("\ntokenizador verificado:", "SÍ" if ok_total else "NO")
    (RAIZ / "resultados" / "ETAPA4_fase1_tokenizador.json").write_text(json.dumps({"comparacion": res, "casos": filas, "chequeos": chequeos, "ok": ok_total}, ensure_ascii=False, indent=1), encoding="utf-8")


# ------------------------------------------------------------------ 3. empaquetado
class Empaquetador:
    """Acumula tokens y escribe shards uint16 de `por_shard` tokens (los documentos van separados por <|fin|>)."""

    def __init__(self, nombre, por_shard=100_000_000):
        self.nombre, self.por_shard = nombre, por_shard
        self.buf, self.n_buf, self.shards, self.tokens = [], 0, [], 0
        CORPUS.mkdir(parents=True, exist_ok=True)

    def poner(self, ids):
        a = np.asarray(ids, dtype=np.uint16)
        self.buf.append(a)
        self.n_buf += len(a)
        self.tokens += len(a)
        if self.n_buf >= self.por_shard:
            self.volcar()

    def volcar(self):
        if not self.buf:
            return
        ruta = CORPUS / f"{self.nombre}_{len(self.shards):03d}.bin"
        np.concatenate(self.buf).tofile(ruta)
        self.shards.append({"archivo": ruta.name, "tokens": self.n_buf})
        self.buf, self.n_buf = [], 0


def cmd_empaquetar(solo_informe=False):
    from tokenizers import Tokenizer

    tok = Tokenizer.from_file(str(TOK_V2))
    eos = tok.token_to_id("<|fin|>")
    tok.no_truncation()
    t0 = time.time()
    # --- descontaminación: n-gramas de 13 tokens de TODO el texto de evaluación de las Etapas 1-4
    textos, titulos, por_archivo = textos_de_evaluacion()
    hs = [hashes_ngramas(e.ids) for e in tok.encode_batch(textos)]
    ev_hash = np.unique(np.concatenate([h for h in hs if len(h)])) if any(len(h) for h in hs) else np.empty(0, dtype=np.uint64)
    print(f"descontaminación: {len(textos):,} textos de evaluación en {len(por_archivo)} archivos -> {len(ev_hash):,} n-gramas de {NGRAMA} tokens y {len(titulos):,} títulos reservados "
          f"({time.time() - t0:.0f}s)", flush=True)
    informe = {"evaluaciones": por_archivo, "ngramas_unicos": int(len(ev_hash)), "titulos_reservados": len(titulos), "fuentes": {}}
    vistos = set()  # deduplicación exacta (los 2.000 primeros caracteres) entre todas las fuentes
    val = Empaquetador("val", por_shard=10**12)

    def procesar(generador, presupuestos, filtro):
        """Una pasada: filtra, deduplica, tokeniza por lotes, descontamina y empaqueta cada documento en su destino (`dest`) hasta llenar su presupuesto."""
        emps = {d: Empaquetador(d) for d in presupuestos}
        causas = {d: Counter() for d in presupuestos}
        lote, meta = [], []
        t1 = time.time()
        leidos = 0

        def llenos():
            return all(emps[d].tokens >= presupuestos[d] for d in presupuestos)

        def vaciar():
            nonlocal lote, meta
            for (texto, dest), e in zip(meta, tok.encode_batch(lote)):
                ids = e.ids
                h = hashes_ngramas(ids)
                if len(h) and len(ev_hash) and bool((ev_hash[np.minimum(np.searchsorted(ev_hash, h), len(ev_hash) - 1)] == h).any()):
                    causas[dest]["CONTAMINADO (n-grama de evaluación)"] += 1
                    continue
                if emps[dest].tokens >= presupuestos[dest]:
                    causas[dest]["presupuesto_lleno"] += 1
                    continue
                (val if h8(texto) % 500 == 0 else emps[dest]).poner(ids + [eos])
            lote, meta = [], []

        for r in generador:
            leidos += 1
            d = r["dest"]
            if emps[d].tokens >= presupuestos[d]:
                continue
            motivo = filtro(r)
            if motivo:
                causas[d][motivo] += 1
                continue
            clave = hashlib.md5(r["texto"][:2000].encode("utf-8", "ignore")).digest()
            if clave in vistos:
                causas[d]["duplicado_exacto"] += 1
                continue
            vistos.add(clave)
            lote.append(r["texto"])
            meta.append((r["texto"], d))
            if len(lote) >= 1024:
                vaciar()
                if leidos % 20480 < 1024:
                    print("  " + " | ".join(f"{k} {e.tokens / 1e6:.0f}/{presupuestos[k] / 1e6:.0f} M" for k, e in emps.items()) + f" | {leidos:,} docs | {time.time() - t1:.0f}s", flush=True)
                if llenos():
                    break
        vaciar()
        for d, emp in emps.items():
            emp.volcar()
            informe["fuentes"][d] = {"tokens": emp.tokens, "shards": emp.shards, "docs_leidos": leidos, "descartes": dict(causas[d]), "segundos": round(time.time() - t1)}
            print(f"{d}: {emp.tokens / 1e6:.0f} M tokens ({len(emp.shards)} shards) | descartes {dict(causas[d])}", flush=True)

    if solo_informe:
        return

    # --- Wikipedia es (≈ 55 % de los artículos, elegidos por hash; se excluyen los artículos reservados para evaluar y lo que no es artículo)
    def wiki():
        for r in iter_wiki():
            if h8(r["title"]) % 100 < 55:
                yield {"texto": r["text"].strip(), "titulo": r["title"], "dest": "wiki"}

    def f_wiki(r):
        if re.sub(r"\W+", " ", r["titulo"].lower()).strip() in titulos:
            return "TITULO_RESERVADO"
        if r["titulo"].startswith(("Anexo:", "Wikipedia:", "Plantilla:")):
            return "no_articulo"
        return "corto" if len(r["texto"]) < 500 else None

    procesar(wiki(), {"wiki": PRESUPUESTO["wiki"]}, f_wiki)

    # --- Web (FineWeb-2): una sola pasada, la cuota latinoamericana y la del resto se llenan por separado
    def web():
        for r in iter_web():
            yield {"texto": r["text"][:60000].strip(), "score": r["language_score"], "dest": "web_latam" if es_latam(r["url"]) else "web_otros"}

    procesar(web(), {"web_latam": PRESUPUESTO["web_latam"], "web_otros": PRESUPUESTO["web_otros"]}, lambda r: filtro_web(r["texto"], r["score"]))

    # --- Código y documentación: cuota por lenguaje
    por_leng = Counter()

    def codigo():
        for r in iter_codigo():
            if r["language"] in CUOTA_CODIGO:
                yield {"texto": f"# archivo: {r['path']}\n" + r["code"], "code": r["code"], "license": r["license"], "language": r["language"], "dest": "codigo"}

    def f_cod(r):
        m = filtro_codigo(r)
        if m:
            return m
        cupo = CUOTA_CODIGO[r["language"]] * PRESUPUESTO["codigo"] * 4.2  # caracteres aproximados por lenguaje
        if por_leng[r["language"]] >= cupo:
            return "cuota_de_lenguaje"
        por_leng[r["language"]] += len(r["code"])
        return None

    procesar(codigo(), {"codigo": PRESUPUESTO["codigo"]}, f_cod)
    informe["fuentes"]["codigo"]["caracteres_por_lenguaje"] = dict(por_leng)
    val.volcar()
    informe["validacion"] = {"tokens": val.tokens, "shards": val.shards}
    total = sum(v["tokens"] for v in informe["fuentes"].values())
    informe["total_tokens_entrenamiento"] = total
    informe["segundos_totales"] = round(time.time() - t0)
    (CORPUS / "manifiesto.json").write_text(json.dumps(informe, ensure_ascii=False, indent=1), encoding="utf-8")
    (RAIZ / "resultados" / "ETAPA4_fase1_corpus.json").write_text(json.dumps(informe, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\nCorpus empaquetado: {total / 1e9:.3f} B tokens de entrenamiento + {val.tokens / 1e6:.1f} M de validación en {informe['segundos_totales']} s", flush=True)


def cmd_verificar_descontaminacion():
    """Comprobación INDEPENDIENTE sobre los shards ya empaquetados: ningún n-grama de 13 tokens de los textos de evaluación aparece en el corpus
    (y, como informe, cuántos de 8 tokens: las coincidencias cortas son inevitables en español: «de acuerdo con la», «es un municipio de»…)."""
    from tokenizers import Tokenizer

    tok = Tokenizer.from_file(str(TOK_V2))
    textos, titulos, por_archivo = textos_de_evaluacion()
    enc = tok.encode_batch(textos)
    res = {}
    for n in (13, 8):
        hs = [hashes_ngramas(e.ids, n) for e in enc]
        ev = np.unique(np.concatenate([h for h in hs if len(h)]))
        # control positivo: una evaluación metida en un arreglo SÍ se detecta
        ctrl = np.array(max(enc, key=lambda e: len(e.ids)).ids, dtype=np.uint16)  # el texto más largo (los cortos no tienen n-gramas)
        h = hashes_ngramas(ctrl, n)
        assert len(h) > 0 and bool((ev[np.minimum(np.searchsorted(ev, h), len(ev) - 1)] == h).any()), "el control positivo no se detectó"
        golpes, total, por_fuente = 0, 0, Counter()
        for ruta in sorted(CORPUS.glob("*.bin")):
            a = np.fromfile(ruta, dtype=np.uint16)
            for i in range(0, len(a), 20_000_000):
                trozo = a[i:i + 20_000_000 + n]
                h = hashes_ngramas(trozo, n)
                ok = ev[np.minimum(np.searchsorted(ev, h), len(ev) - 1)] == h
                g = int(ok.sum())
                golpes += g
                por_fuente[ruta.name.rsplit("_", 1)[0]] += g
            total += len(a)
        res[f"n={n}"] = {"ngramas_de_evaluacion": int(len(ev)), "tokens_revisados": int(total), "coincidencias": int(golpes), "por_fuente": dict(por_fuente)}
        print(f"n={n:2d}: {len(ev):,} n-gramas de evaluación vs {total / 1e9:.3f} B tokens del corpus -> {golpes:,} coincidencias {dict(por_fuente)}", flush=True)
    (RAIZ / "resultados" / "ETAPA4_fase1_descontaminacion.json").write_text(json.dumps(res, indent=1), encoding="utf-8")


