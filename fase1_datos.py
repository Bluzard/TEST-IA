# ------------------------------------------------------------------ filtros
def filtro_web(t, score):
    """None si el documento web sirve; si no, el motivo del descarte."""
    if score is not None and score < 0.90:
        return "idioma"
    n = len(t)
    if n < 400:
        return "corto"
    palabras = t.split()
    nw = len(palabras)
    if nw < 60:
        return "corto"
    if not 3.0 <= n / nw <= 10.0:
        return "longitud_de_palabra"
    muestra = t[:5000]
    if sum(c.isalpha() for c in muestra) / len(muestra) < 0.6:
        return "pocas_letras"
    if sum(w.lower() in STOP_ES for w in palabras[:300]) < 12:
        return "no_espanol"
    lineas = [l for l in t.split("\n") if l.strip()]
    if len(lineas) > 5:
        if len(set(lineas)) / len(lineas) < 0.7:
            return "lineas_repetidas"
        if sum(l.lstrip()[:1] in "-*•·|>" for l in lineas) / len(lineas) > 0.7:
            return "listas"
        if sum(l.rstrip()[-1:] in ".!?:;»\")" for l in lineas) / len(lineas) < 0.10:
            return "sin_puntuacion"
    if t.count("#") + t.count("...") > 0.1 * nw:
        return "simbolos"
    if re.search(r"lorem ipsum", t, re.I):
        return "relleno"
    return None


def filtro_codigo(r):
    c = r["code"]
    if r["license"] not in LICENCIAS_OK:
        return "licencia"
    if not 200 <= len(c) <= 60_000:
        return "tamano"
    lineas = c.split("\n")
    if max(len(l) for l in lineas) > 1000 or len(c) / max(1, len(lineas)) > 100:
        return "lineas_largas"
    if sum(ch.isalnum() for ch in c[:5000]) / len(c[:5000]) < 0.25:
        return "pocos_alfanumericos"
    if AUTOGEN.search(c[:1500]):
        return "autogenerado"
    if SECRETOS.search(c):
        return "secretos"
    return None


# ------------------------------------------------------------------ lectura de los parquet descargados
def iter_parquet(archivos, columnas, lote=2000):
    for a in archivos:
        pf = pq.ParquetFile(a)
        for b in pf.iter_batches(batch_size=lote, columns=columnas):
            d = b.to_pydict()
            for i in range(len(d[columnas[0]])):
                yield {k: d[k][i] for k in columnas}


def archivos(carpeta, patron):
    return sorted((RAW / carpeta).rglob(patron))


def iter_wiki():
    for r in iter_parquet(archivos("wikipedia", "*.parquet"), ["title", "text"]):
        yield r


def iter_web():
    """Intercala los shards de FineWeb-2 para mezclar dumps distintos."""
    its = [iter_parquet([a], ["text", "url", "language_score"]) for a in archivos("fineweb2", "*.parquet")]
    vivos = list(its)
    while vivos:
        for it in list(vivos):
            try:
                yield next(it)
            except StopIteration:
                vivos.remove(it)


def iter_codigo():
    its = [iter_parquet([a], ["code", "language", "license", "path"]) for a in archivos("codigo", "*.parquet")]
    vivos = list(its)
    while vivos:
        for it in list(vivos):
            try:
                yield next(it)
            except StopIteration:
                vivos.remove(it)


