def textos_de_evaluacion():
    """Todo el texto de los conjuntos de evaluación de las Etapas 1-4 y los títulos de artículos reservados."""
    rutas = sorted(set((RAIZ / "datos").glob("*eval*.jsonl")) | set((RAIZ / "datos").glob("evaluacion*.jsonl")) |
                   set((RAIZ / "estudios").rglob("*eval*.jsonl")) | set((V2 / "eval").glob("*.jsonl")) | set((RAIZ / "datos" / "eval_v2").glob("*.jsonl")))
    textos, titulos, por_archivo = [], set(), {}
    for ruta in rutas:
        n = 0
        for linea in open(ruta, encoding="utf-8"):
            try:
                r = json.loads(linea)
            except json.JSONDecodeError:
                continue
            for k, v in r.items():
                if isinstance(v, str) and len(v) > 8:
                    textos.append(v)
                    n += 1
            for k in ("consulta", "titulo"):
                if isinstance(r.get(k), str):
                    titulos.add(re.sub(r"\W+", " ", r[k].lower()).strip())
        por_archivo[ruta.name if ruta.parent.name in ("datos", "v2", "eval_v2", "eval") else f"{ruta.parent.name}/{ruta.name}"] = n
    return textos, titulos, por_archivo


NGRAMA = 13
_P = np.uint64(1000003)


def hashes_ngramas(ids, n=NGRAMA):
    """Hash rodante (polinomial, 64 bits) de todos los n-gramas de tokens de un arreglo."""
    a = np.asarray(ids, dtype=np.uint64)
    if len(a) < n:
        return np.empty(0, dtype=np.uint64)
    h = np.zeros(len(a) - n + 1, dtype=np.uint64)
    with np.errstate(over="ignore"):
        for k in range(n):
            h = h * _P + a[k:len(a) - n + 1 + k]
    return h


# ------------------------------------------------------------------ 1. muestra del tokenizador
def cmd_muestra(mb=400):
    V2.mkdir(parents=True, exist_ok=True)
    rng = random.Random(0)
    cuotas = {"wiki": 0.25, "web": 0.35, "codigo": 0.22, "protocolo": 0.10, "gramatica_tecnica": 0.08}
    objetivo = {k: int(v * mb * 1e6) for k, v in cuotas.items()}
    escrito = Counter()
    t0 = time.time()
    with open(MUESTRA, "w", encoding="utf-8") as f:
        def poner(fuente, t):
            f.write(t.strip() + "\n\x01\n")
            escrito[fuente] += len(t.encode("utf-8"))

        for r in iter_wiki():
            if escrito["wiki"] >= objetivo["wiki"]:
                break
            if h8(r["text"]) % 1000 != 7 and len(r["text"]) > 500 and rng.random() < 0.15:  # los h8 % 1000 == 7 quedan fuera: sirven para comparar
                poner("wiki", r["text"])
        print(f"  wiki {escrito['wiki'] / 1e6:.0f} MB | {time.time() - t0:.0f}s", flush=True)
        for r in iter_web():
            if escrito["web"] >= objetivo["web"]:
                break
            if h8(r["text"]) % 1000 != 7 and filtro_web(r["text"], r["language_score"]) is None and rng.random() < 0.10:
                poner("web", r["text"][:20000])
        print(f"  web {escrito['web'] / 1e6:.0f} MB | {time.time() - t0:.0f}s", flush=True)
        por_leng = Counter()
        for r in iter_codigo():
            if escrito["codigo"] >= objetivo["codigo"]:
                break
            lg = r["language"]
            if lg not in CUOTA_CODIGO or filtro_codigo(r) is not None or h8(r["code"]) % 1000 == 7:
                continue
            if por_leng[lg] >= CUOTA_CODIGO[lg] * objetivo["codigo"]:
                continue
            por_leng[lg] += len(r["code"])
            poner("codigo", f"# archivo: {r['path']}\n" + r["code"])
        print(f"  código {escrito['codigo'] / 1e6:.0f} MB {dict((k, round(v / 1e6)) for k, v in por_leng.items())} | {time.time() - t0:.0f}s", flush=True)
        # texto de protocolo y de oficio del proyecto: conversaciones con B:/R:/E:, preguntas y respuestas, salidas de Python, reglas gramaticales
        for nombre in ("sft_train.jsonl", "experto_train_B2.jsonl", "redaccion_train.jsonl"):
            for linea in open(RAIZ / "datos" / nombre, encoding="utf-8"):
                r = json.loads(linea)
                partes = [r.get("pregunta", "")]
                if r.get("consulta"):
                    partes.append(f"{r.get('pref', 'B')}: {r['consulta']}")
                if r.get("resultados"):
                    partes.append(r["resultados"])
                partes.append(f"R: {r.get('respuesta', '')}")
                poner("protocolo", "\n".join(p for p in partes if p))
                if escrito["protocolo"] >= objetivo["protocolo"]:
                    break
        from redaccion_fichas import FICHAS_GRAMATICA
        from experto_fichas import FICHAS

        for ficha in list(FICHAS) + list(FICHAS_GRAMATICA):
            for _ in range(20):  # pocas fichas: se repiten para que su vocabulario técnico cuente
                poner("gramatica_tecnica", f"{ficha[0]}: {ficha[2]}\nEjemplo: {ficha[3] or ''}")
    print("muestra:", {k: f"{v / 1e6:.1f} MB" for k, v in escrito.items()}, f"-> {MUESTRA} ({MUESTRA.stat().st_size / 1e6:.0f} MB)", flush=True)


# ------------------------------------------------------------------ 2. tokenizador
def documentos(ruta):
    buf = []
    with open(ruta, encoding="utf-8") as f:
        for linea in f:
            if linea == "\x01\n":
                if buf:
                    yield "".join(buf).strip()
                buf = []
            else:
                buf.append(linea)


def cmd_tokenizador():
    from tokenizers import Tokenizer, decoders, models, pre_tokenizers, trainers

    tok = Tokenizer(models.BPE())
    tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)  # igual que v1: el motor y las herramientas no cambian
    tok.decoder = decoders.ByteLevel()
    entrenador = trainers.BpeTrainer(vocab_size=VOCAB, special_tokens=ESPECIALES, initial_alphabet=pre_tokenizers.ByteLevel.alphabet(), show_progress=False)
    t0 = time.time()
    print(f"Entrenando el BPE de {VOCAB} tokens con {MUESTRA.stat().st_size / 1e6:.0f} MB...", flush=True)
    tok.train_from_iterator(documentos(MUESTRA), entrenador)
    tok.save(str(TOK_V2))
    sft = Tokenizer.from_file(str(TOK_V2))
    sft.add_special_tokens(ETIQUETAS)  # las 4 etiquetas de turno al final (ids 24000-24003), como en v1
    sft.save(str(TOK_V2_SFT))
    print(f"listo en {time.time() - t0:.0f}s: {sft.get_vocab_size()} tokens -> {TOK_V2_SFT}", flush=True)
    comparar()


